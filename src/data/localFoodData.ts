export function searchLocalFoods(query: string): LocalFoodItem[] {
  if (!query || query.trim() === '') return PALEMBANG_LOCAL_FOODS;
  const cleanQ = query.toLowerCase().trim();
  return PALEMBANG_LOCAL_FOODS.filter(
    (item) =>
      item.name.toLowerCase().includes(cleanQ) ||
      item.category.toLowerCase().includes(cleanQ) ||
      item.description.toLowerCase().includes(cleanQ)
  );
}
